/**
 * Hardcoded Node Configuration Definitions
 * Maps node types to their configuration fields
 * Loads instantly without API calls
 * 
 * Architecture follows n8n's hybrid approach:
 * - Input fields: Configuration parameters
 * - Output fields: Data available to downstream nodes
 */

export type FieldValueType =
  | 'text' | 'textarea' | 'number' | 'boolean' | 'select' | 'password' | 'email' | 'url'
  // rendered by components/workflows/fields/ConnectionFields.tsx
  | 'schedule' | 'localModel' | 'mcpServer' | 'mcpServers' | 'mcpTool' | 'mcpArgs';
export type OutputFieldType = 'string' | 'number' | 'boolean' | 'object' | 'array' | 'date' | 'json';

export interface NodeField {
  name: string;
  label: string;
  type: FieldValueType;
  placeholder?: string;
  description?: string;
  required?: boolean;
  options?: Array<{ label: string; value: string }>;
  validation?: {
    min?: number;
    max?: number;
    pattern?: string;
    message?: string;
  };
  group?: string;
  rows?: number;
  halfWidth?: boolean;
  /** Show this field only while another field has one of these values (`default` stands in when it is unset). */
  showWhen?: { field: string; in: string[]; default?: string };
  /** On a select: choosing an option also fills in these other fields (for example a mail provider's server). */
  presets?: Record<string, Record<string, string | number | boolean>>;
  /** A short "where do I get this" note under the field, with an optional link. */
  help?: { text: string; url?: string; label?: string };
}

export interface OutputField {
  name: string;
  path: string[];
  type: OutputFieldType;
  description: string;
  children?: OutputField[];
}

export interface NodeOutput {
  type: 'main' | 'error';
  displayName?: string;
  fields: OutputField[];
  dynamic?: boolean; // Indicates fields may vary at runtime
}

export interface NodeDefinition {
  type: string;
  name: string;
  description: string;
  category: string;
  fields: NodeField[];
  outputs?: Record<string, NodeOutput>;
}

